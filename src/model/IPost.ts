// Інтерфейс IPost описує структуру одного поста,
// який отримуємо з API JSONPlaceholder.
// Визначає назви властивостей та типи даних,
// які повинен містити об'єкт поста.
export interface IPost {
	// Ідентифікатор користувача, який створив цей пост.
	// За допомогою userId можна визначити, якому користувачу належить пост.тип даних number
	userId: number;
	// Унікальний ідентифікатор самого поста.тип даних number
	id: number;
	// Заголовок поста.Значення зберігається у вигляді рядка
	title: string;
	// Основний текст або вміст поста.Значення зберігається у вигляді рядка
	body: string;
}
