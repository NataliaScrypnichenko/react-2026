// Інтерфейс IComment описує структуру одного коментаря,
// який отримуємо з API JSONPlaceholder.
// Визначає властивості та типи даних,
// які повинен містити об'єкт коментаря.
export interface IComment {
    // Ідентифікатор поста, до якого належить цей коментар.
    // За допомогою postId можна визначити,
    // під яким постом потрібно відобразити коментар.
    postId: number;
    // Унікальний ідентифікатор самого коментаря.
    id: number;
    // Ім'я автора коментаря.
    name: string;
    // Електронна адреса автора коментаря.
    email: string;
    // Основний текст коментаря.
    body: string;
}
