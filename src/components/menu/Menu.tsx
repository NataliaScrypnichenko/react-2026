// Імпортую компонент Link з бібліотеки react-router.
// Link використовується для переходу між сторінками без повного перезавантаження сайту.
import { Link } from "react-router";

// Створюю функціональний компонент Menu,
// який відповідає за відображення навігаційного меню застосунку.
const Menu = () => {

    // За допомогою return повертаю розмітку,яка визначає структуру навігаційного меню.
    return (

        // div — загальний HTML-контейнер для розміщення елементів меню.
        <div>

            {/* ul створює ненумерований список для розміщення пунктів навігації. */}
            <ul>

                {/* li створює окремий пункт списку.
                    Link створює посилання для переходу на сторінку користувачів.
                    Властивість to вказує адресу маршруту /users.
                    Текст users відображається як назва посилання. */}
                <li>
                    <Link to={'/users'}>users</Link>
                </li>

                {/* li створює окремий пункт списку.
                    Link створює посилання для переходу на сторінку постів.
                    Властивість to вказує адресу маршруту /posts.
                    Текст posts відображається як назва посилання. */}
                <li>
                    <Link to={'/posts'}>posts</Link>
                </li>

                {/* li створює окремий пункт списку.
                    Link створює посилання для переходу на сторінку коментарів.
                    Властивість to вказує адресу маршруту /comments.
                    Текст comments відображається як назва посилання. */}
                <li>
                    <Link to={'/comments'}>comments</Link>
                </li>

                {/* li створює окремий пункт списку.
                    Link створює посилання для переходу на комплексну сторінку.
                    Властивість to вказує адресу маршруту /complex.
                    На цій сторінці відображаються користувачі, їхні пости та коментарі. */}
                <li>
                    <Link to={'/complex'}>complex</Link>
                </li>

            </ul>
        </div>
    );
};

// Експортую компонент Menu за допомогою export default,
// щоб його можна було імпортувати та використовувати в інших компонентах,
// зокрема в компоненті App.
export default Menu;
