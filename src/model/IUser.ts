// Інтерфейс IUser описує структуру об'єкта користувача.
// Визначає, які властивості повинен містити об'єкт користувача
// та який тип даних повинна мати кожна властивість.
export interface IUser {
	// Унікальний числовий ідентифікатор користувача.
	id: number;
	// Ім'я та прізвище користувача.
	name: string;
	// Ім'я користувача, яке використовується як його нікнейм.
	username: string;
	// Електронна адреса користувача.
	email: string;
	// Адреса користувача.
	// Тип Address означає, що ця властивість містить вкладений об'єкт
	// зі структурою, описаною в інтерфейсі Address.
	address: Address;
	// Номер телефону користувача.
	phone: string;
	// Вебсайт користувача.
	website: string;
	// Інформація про компанію, до якої належить користувач.
	// Тип Company означає, що властивість містить вкладений об'єкт
	// зі структурою, описаною в інтерфейсі Company.
	company: Company;
}

// Інтерфейс AddressGeo описує географічні координати адреси користувача.
// Координати складаються з широти та довготи.
export interface AddressGeo {
	// Географічна широта — визначає положення точки на північ або південь.
	// Значення зберігається у вигляді рядка.
	lat: string;
	// Географічна довгота — визначає положення точки на схід або захід.
	// Значення зберігається у вигляді рядка.
	lng: string;
}

// Інтерфейс Address описує структуру адреси користувача.
// Містить інформацію про вулицю, квартиру, місто, поштовий індекс
// та географічні координати.
export interface Address {
	// Назва вулиці, на якій проживає користувач.
	street: string;
	// Номер квартири або додаткова інформація про адресу.
	suite: string;
	// Назва міста, в якому проживає користувач.
	city: string;
	// Поштовий індекс адреси.
	zipcode: string;
	// Географічні координати адреси.
	// Тип AddressGeo означає, що всередині цієї властивості
	// знаходиться об'єкт із властивостями lat та lng.
	geo: AddressGeo;
}

// Інтерфейс Company описує інформацію про компанію користувача.
// Визначає назву компанії та додаткову інформацію про її діяльність.
export interface Company {
	// Назва компанії.
	name: string;
	// Короткий рекламний вислів або опис компанії.
	catchPhrase: string;
	// Короткий опис напряму діяльності або бізнес-моделі компанії.
	bs: string;
}
