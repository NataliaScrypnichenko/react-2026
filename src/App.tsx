// Імпортую CSS-файл зі стилями для компонента App
import './App.css'

// Імпортую Outlet для відображення вкладених маршрутів React Router
import { Outlet } from "react-router";

// Імпортую компонент Menu, який містить навігаційні посилання
import Menu from "./components/menu/Menu.tsx";

// Створюю кореневий функціональний компонент App,який визначає загальну структуру сторінки.
function App() {

    // Повертаю розмітку, яка визначає структуру компонента
    return (
        // Fragment дозволяє об'єднати декілька елементів без додаткового div
        <>
            {/* Відображає навігаційне меню. Воно залишається на сторінці під час переходу між вкладеними маршрутами,
            тому що App використовується як їхній спільний батьківський компонент. */}
            <Menu/>

            {/* Outlet відображає компонент відповідного вкладеного маршруту то б то це місце,
             де React Router відображає компонент поточного дочірнього маршруту */}
            <Outlet/>
        </>
    )
}

// Експортую компонент App, щоб використовувати його в маршрутах
export default App;
